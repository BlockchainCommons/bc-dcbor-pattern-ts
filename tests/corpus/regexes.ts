/** Every source over every subject of its mode. */
export function* regexes(): Generator<Recipe> {
  for (const src of TEXT_SOURCES) {
    for (const subject of TEXT_SUBJECTS) yield { k: "regex", src, mode: "text", subject };
  }
  for (const src of BYTE_SOURCES) {
    for (const subject of BYTE_SUBJECTS) yield { k: "regex", src, mode: "bytes", subject };
  }
}
